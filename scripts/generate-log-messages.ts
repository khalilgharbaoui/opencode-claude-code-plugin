/**
 * Regenerate `src/log-messages.ts` from the `log.*()` calls in `src/`.
 *
 * Run `npm run generate:log-messages` after adding or changing a NOTICE, WARN
 * or ERROR message. `test-diagnostic-bundle.ts` re-runs the same scan and fails
 * when the committed file has drifted, so this is never optional: a message
 * missing from the set is redacted out of `/claude-code-doctor bundle`.
 */
import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { bundledMessages, scanLogMessages } from "../src/log-message-scan.js"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const scan = scanLogMessages(join(root, "src"))
const messages = bundledMessages(scan)

const body = [
  "// GENERATED by scripts/generate-log-messages.ts. Do not edit by hand.",
  "// Run `npm run generate:log-messages` after changing a NOTICE, WARN or",
  "// ERROR message; test-diagnostic-bundle.ts fails when this file drifts.",
  "",
  "/**",
  " * Every NOTICE, WARN and ERROR message in this package whose text is a",
  " * plugin-authored constant. `/claude-code-doctor bundle` prints a log line's",
  " * message verbatim only when it is in here; anything else is redacted,",
  " * because a message built at runtime can carry data this package did not",
  " * write. See src/log-message-scan.ts.",
  " */",
  "export const PLUGIN_LOG_MESSAGES: ReadonlySet<string> = new Set([",
  ...messages.map((message) => `  ${JSON.stringify(message)},`),
  "])",
  "",
].join("\n")

writeFileSync(join(root, "src", "log-messages.ts"), body, "utf8")
console.log(`src/log-messages.ts: ${messages.length} messages, ${scan.dynamic.length} dynamic sites`)
for (const site of scan.dynamic) {
  console.log(`  dynamic ${site.level.padEnd(6)} ${site.file}:${site.line} (${site.kind})`)
}
